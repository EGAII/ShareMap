// Makes the generated style files from the website's own sources, so both look the same:
//   styles/icons.wxss  — the icon set in index.html, as CSS masks (colored with currentColor)
//   styles/covers.wxss — the place-cover colors of css/style.css (.hue-*), light and dark
// Mini programs can't show inline <svg> or compute calc() inside hsl(), hence this step.
// Run after changing icons or cover colors:  node miniprogram/tools/build-styles.js
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..', '..');
const out = path.join(__dirname, '..', 'styles');
const head = (what) => `/* Generated by tools/build-styles.js from ${what}. Don't edit by hand. */\n`;

// ---------------------------------------------------------------------
// Icons
// ---------------------------------------------------------------------
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const icons = {};
for (const m of html.matchAll(/<symbol id="i-([\w-]+)" viewBox="0 0 24 24">([\s\S]*?)<\/symbol>/g)) icons[m[1]] = m[2];
// Extra glyphs the mini program needs (same stroke style)
icons['chevron-down'] = '<path d="M6.5 9.5 12 15l5.5-5.5"/>';
const stroke = (inner) => '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="#000" '
  + `stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round">${inner}</svg>`;
// The logo's pin (index.html .logo), solid with the hole cut out
const logoPin = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24"><path fill="#000" fill-rule="evenodd" '
  + 'd="M12 19.5s-5.2-4.5-5.2-8.5a5.2 5.2 0 0 1 10.4 0c0 4-5.2 8.5-5.2 8.5zM12 9.1a1.9 1.9 0 1 0 0 3.8a1.9 1.9 0 1 0 0-3.8z"/></svg>';
const b64 = (svg) => Buffer.from(svg).toString('base64');
const mask = (svg) => { const u = `url("data:image/svg+xml;base64,${b64(svg)}")`; return `-webkit-mask-image: ${u}; mask-image: ${u};`; };

let css = head('the <symbol> icons in index.html');
for (const [name, inner] of Object.entries(icons).sort()) css += `.i-${name} { ${mask(stroke(inner))} }\n`;
css += `.i-logo-pin { ${mask(logoPin)} }\n`;
fs.writeFileSync(path.join(out, 'icons.wxss'), css);

// ---------------------------------------------------------------------
// Place-cover colors: .cover in css/style.css, one block per hue
// ---------------------------------------------------------------------
const styleCss = fs.readFileSync(path.join(root, 'css', 'style.css'), 'utf8');
const hues = { n: [40, 8] };
for (const m of styleCss.matchAll(/\.hue-(\d) \{ --h: (\d+);\s*--s: (\d+)%; \}/g)) hues[m[1]] = [Number(m[2]), Number(m[3])];
if (Object.keys(hues).length !== 7) throw new Error('Expected .hue-0 … .hue-5 in css/style.css');

function hsl(h, s, l, a) {
  s = Math.min(100, s) / 100; l /= 100;
  const k = (n) => (n + h / 30) % 12;
  const f = (n) => l - s * Math.min(l, 1 - l) * Math.max(-1, Math.min(k(n) - 3, 9 - k(n), 1));
  const [r, g, b] = [f(0), f(8), f(4)].map((x) => Math.round(x * 255));
  return a == null ? '#' + [r, g, b].map((x) => x.toString(16).padStart(2, '0')).join('') : `rgba(${r}, ${g}, ${b}, ${a})`;
}
// The formulas of .cover (light) and its prefers-color-scheme: dark block
const light = (h, s) => ({ bg: hsl(h, s * 0.9, 91), bg2: hsl(h, s, 84), line: hsl(h, s, 50), ink: hsl(h, s + 12, 16), chip: hsl(h, 30, 99, 0.74) });
const dark = (h, s) => ({ bg: hsl(h, s * 0.7, 22), bg2: hsl(h, s * 0.55, 15), line: hsl(h, s, 46), ink: hsl(h, s * 0.6, 93), chip: hsl(h, 15, 8, 0.5) });
const vars = (c) => `--cv-bg: ${c.bg}; --cv-bg2: ${c.bg2}; --cv-line: ${c.line}; --cv-ink: ${c.ink}; --cv-chip: ${c.chip};`;

css = head('the .cover and .hue-* colors in css/style.css');
for (const [k, [h, s]] of Object.entries(hues)) css += `.hue-${k} { ${vars(light(h, s))} }\n`;
css += '@media (prefers-color-scheme: dark) {\n';
for (const [k, [h, s]] of Object.entries(hues)) css += `  .hue-${k} { ${vars(dark(h, s))} }\n`;
css += '}\n';
fs.writeFileSync(path.join(out, 'covers.wxss'), css);

// The same colors for the drawn pattern (utils/cover.js draws it as an image, which can't use CSS variables)
const js = '// Generated by tools/build-styles.js from css/style.css. Don\'t edit by hand.\n'
  + `module.exports = ${JSON.stringify(Object.fromEntries(Object.entries(hues).map(([k, [h, s]]) =>
    [`hue-${k}`, { light: { line: light(h, s).line, ink: light(h, s).ink }, dark: { line: dark(h, s).line, ink: dark(h, s).ink } }])), null, 2)};\n`;
fs.writeFileSync(path.join(__dirname, '..', 'utils', 'cover-colors.js'), js);

console.log(`icons: ${Object.keys(icons).length + 1}, hues: ${Object.keys(hues).length}`);
